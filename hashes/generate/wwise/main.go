package main

import (
	"bytes"
	"context"
	"maps"
	"os"
	"slices"

	"github.com/jwalton/go-supportscolor"
	"github.com/xypwn/filediver/app"
	"github.com/xypwn/filediver/hashes/generate/wwise/banks"
	"github.com/xypwn/filediver/hashes/generate/wwise/deps"
	"github.com/xypwn/filediver/hashes/generate/wwise/streams"
	"github.com/xypwn/filediver/stingray"
)

func main() {
	prt := app.NewConsolePrinter(
		supportscolor.Stderr().SupportsColor,
		os.Stderr,
		os.Stderr,
	)

	gameDir, err := app.DetectGameDir()
	if err == nil {
		prt.Infof("Using game found at: \"%v\"", gameDir)
	} else {
		prt.Errorf("Helldivers 2 Steam installation path not found: %v\n", err)
		prt.Fatalf("Command line option for installation path not implemented in wwise generator. Please open an issue on GitHub")
	}
	ctx := context.Background() // no need to exit cleanly since we're only reading
	a, err := app.OpenGameDir(ctx, gameDir, nil, nil, stingray.ThinHash{}, func(curr, total int) {
		prt.Statusf("Reading metadata %.0f%%", float64(curr)/float64(total)*100)
	})
	if err != nil {
		prt.Fatalf("Error opening game dir: %v", err)
	}
	prt.NoStatus()

	genWwiseStreams := os.Getenv("FILEDIVER_GEN_WWISE_STREAMS")
	if genWwiseStreams == "0" || genWwiseStreams == "" {
		prt.Infof("Set env FILEDIVER_GEN_WWISE_STREAMS=1 to generate wwise stream file names. This requires a HD2 steam installation with ALL LANGUAGE PACKS INSTALLED and takes a few minutes of times.")
	} else {
		prt.Infof("Generating wwise_stream hashes...")
		wwiseStreams := streams.GenStreams(prt, a)
		{
			var b bytes.Buffer
			b.WriteString("# Generated by generate/wwise/streams.\n")
			for _, s := range slices.Sorted(maps.Keys(wwiseStreams)) {
				b.WriteString(s)
				b.WriteString("\n")
			}
			if err := os.WriteFile("wwise_streams.txt", b.Bytes(), 0666); err != nil {
				prt.Fatalf("%v", err)
			}
		}
	}

	prt.Infof("Generating wwise_dep hashes...")
	wwiseDeps := deps.GenDeps(prt, a)
	{
		var b bytes.Buffer
		b.WriteString("# Generated by generate/wwise/deps.\n")
		for _, s := range slices.Sorted(maps.Keys(wwiseDeps)) {
			// Make sure the app has the wwise_dep hashes added so wwise_bank generation can use the bank names
			a.Hashes[stingray.Sum(s)] = s
			b.WriteString(s)
			b.WriteString("\n")
		}
		if err := os.WriteFile("wwise_deps.txt", b.Bytes(), 0666); err != nil {
			prt.Fatalf("%v", err)
		}
	}

	genWwiseBanks := os.Getenv("FILEDIVER_GEN_WWISE_BANKS")
	if genWwiseBanks == "0" || genWwiseBanks == "" {
		prt.Infof("Set env FILEDIVER_GEN_WWISE_BANKS=1 to generate wwise bank file names. This requires a HD2 steam installation with ALL LANGUAGE PACKS INSTALLED.")
	} else {
		prt.Infof("Generating wwise_bank hashes...")
		wwiseBanks := banks.GenBanks(prt, a)
		{
			var b bytes.Buffer
			b.WriteString("# Generated by generate/wwise/banks.\n")
			for _, s := range slices.Sorted(maps.Keys(wwiseBanks)) {
				b.WriteString(s)
				b.WriteString("\n")
			}
			if err := os.WriteFile("wwise_banks.txt", b.Bytes(), 0666); err != nil {
				prt.Fatalf("%v", err)
			}
		}
	}
}
